
import { useEffect, useRef, useState } from 'react';
import type {
  CSSProperties,
  KeyboardEvent,
  MouseEvent,
} from 'react';
import { Link } from 'react-router-dom';
import {
  ArrowLeft,
  RotateCcw,
  Trophy,
  Crosshair,
  Zap,
} from 'lucide-react';

import goaliePhoto from '../assets/game/field_hockey-goalie.png';
import '../components/game/FieldHockeyGame.css';

type Difficulty = 'rookie' | 'varsity' | 'all-american';
type Outcome = 'goal' | 'save' | 'miss';
type Phase = 'ready' | 'flying' | 'result';

type Point = {
  x: number;
  y: number;
};

type Shot = {
  target: Point;
  keeperX: number;
  outcome: Outcome;
  power: number;
  duration: number;
  reaction: number;
};

const MAX_SHOTS = 5;

const DIFFICULTIES = {
  rookie: {
    label: 'ROOKIE',
    predictionError: 22,
    maxTravel: 19,
    reach: 0.75,
    reaction: 230,
  },
  varsity: {
    label: 'VARSITY',
    predictionError: 12,
    maxTravel: 30,
    reach: 1,
    reaction: 135,
  },
  'all-american': {
    label: 'ALL-AMERICAN',
    predictionError: 5,
    maxTravel: 42,
    reach: 1.15,
    reaction: 65,
  },
} as const;

const clamp = (value: number, min: number, max: number) =>
  Math.max(min, Math.min(max, value));

const randomBetween = (min: number, max: number) =>
  Math.random() * (max - min) + min;

export default function FieldHockeyGame() {
  const [difficulty, setDifficulty] =
    useState<Difficulty>('varsity');

  const [power, setPower] = useState(65);

  const [aim, setAim] = useState<Point>({
    x: 75,
    y: 28,
  });

  const [phase, setPhase] = useState<Phase>('ready');

  const [shots, setShots] = useState<Shot[]>([]);

  const [currentShot, setCurrentShot] =
    useState<Shot | null>(null);

  const timerRef =
    useRef<ReturnType<typeof setTimeout> | null>(null);

  const goalRef = useRef<HTMLButtonElement>(null);

  useEffect(() => {
    return () => {
      if (timerRef.current) {
        clearTimeout(timerRef.current);
      }
    };
  }, []);

  const config = DIFFICULTIES[difficulty];

  const goals = shots.filter(
    (shot) => shot.outcome === 'goal'
  ).length;

  const saves = shots.filter(
    (shot) => shot.outcome === 'save'
  ).length;

  const misses = shots.filter(
    (shot) => shot.outcome === 'miss'
  ).length;

  const finished =
    shots.length === MAX_SHOTS && phase === 'result';

  function aimAt(event: MouseEvent<HTMLButtonElement>) {
    if (phase !== 'ready') return;

    // Ignore clicks generated by keyboard activation.
    if (event.detail === 0) return;

    const rect = event.currentTarget.getBoundingClientRect();

    setAim({
      x: clamp(
        ((event.clientX - rect.left) / rect.width) * 100,
        3,
        97
      ),
      y: clamp(
        ((event.clientY - rect.top) / rect.height) * 100,
        3,
        97
      ),
    });
  }

  function keyboardAim(
    event: KeyboardEvent<HTMLButtonElement>
  ) {
    if (phase !== 'ready') return;

    const changes: Record<string, Point> = {
      ArrowLeft: { x: -5, y: 0 },
      ArrowRight: { x: 5, y: 0 },
      ArrowUp: { x: 0, y: -5 },
      ArrowDown: { x: 0, y: 5 },
    };

    const change = changes[event.key];

    if (!change) return;

    event.preventDefault();

    setAim((previous) => ({
      x: clamp(previous.x + change.x, 3, 97),
      y: clamp(previous.y + change.y, 3, 97),
    }));
  }

  function takeShot() {
    if (phase !== 'ready' || shots.length >= MAX_SHOTS) {
      return;
    }

    const goalWidth =
      goalRef.current?.getBoundingClientRect().width ?? 700;

    // Stronger shots travel faster but have more spread.
    const spread =
      power <= 75
        ? 2 + (power / 75) * 4
        : 6 + (power - 75) * 0.48;

    const actualTarget: Point = {
      x: aim.x + randomBetween(-spread, spread),
      y: aim.y + randomBetween(-spread, spread),
    };

    const missed =
      actualTarget.x < 0 ||
      actualTarget.x > 100 ||
      actualTarget.y < 0 ||
      actualTarget.y > 100;

    const duration = Math.round(950 - power * 4);

    // The keeper starts at the center of the goal.
    // His prediction is imperfect, depending on difficulty.
    const predictedX =
      actualTarget.x +
      randomBetween(
        -config.predictionError,
        config.predictionError
      );

    // Fast shots leave less time to move.
    const speedFactor = 1.12 - (power / 100) * 0.38;

    const availableTravel =
      config.maxTravel * speedFactor;

    // IMPORTANT:
    // This is the keeper's actual on-screen destination.
    // He cannot teleport anywhere in the goal.
    const keeperX = clamp(
      predictedX,
      50 - availableTravel,
      50 + availableTravel
    );

    // The visible cutout's central body and pads
    // have a smaller collision area than its full image.
    const bodyHalfWidthPx =
      goalWidth < 450 ? 17 : 33;

    const bodyReachPercent =
      (bodyHalfWidthPx / goalWidth) *
      100 *
      config.reach *
      speedFactor;

    const horizontalDistance = Math.abs(
      actualTarget.x - keeperX
    );

    // The standing goalkeeper cannot save every
    // high corner shot just by moving sideways.
    const inKeeperHeight =
      actualTarget.y >= 30 &&
      actualTarget.y <= 96;

    const saved =
      !missed &&
      horizontalDistance <= bodyReachPercent &&
      inKeeperHeight;


        const outcome: Outcome = missed
        ? 'miss'
        : saved
            ? 'save'
            : 'goal';

        // Visual correction:
        // If it's a goal, the keeper must visibly miss the ball.
        // Move him to the opposite side of the target.
        //
        // For saves, keep the actual calculated keeper position.
        let visualKeeperX = keeperX;

        
        if (outcome === 'goal') {
        // Keeper sprite is wider on desktop than mobile.
        // Reserve enough visual clearance for the photo.
        const spriteWidth = goalWidth < 450 ? 77 : 145;

        const safeDistance =
            ((spriteWidth / 2 + 24) / goalWidth) * 100;

        const missedPosition =
            actualTarget.x < 50
            ? actualTarget.x + safeDistance
            : actualTarget.x - safeDistance;

        visualKeeperX = clamp(missedPosition, 15, 85);
        }


        const shot: Shot = {
        target: actualTarget,
        keeperX: visualKeeperX,
        outcome,
        power,
        duration,
        reaction: config.reaction,
        };

    setCurrentShot(shot);
    setShots((previous) => [...previous, shot]);
    setPhase('flying');

    timerRef.current = setTimeout(() => {
      setPhase('result');
      timerRef.current = null;
    }, duration + 220);
  }

  function nextShot() {
    setCurrentShot(null);
    setPhase('ready');
  }

  function restart() {
    if (timerRef.current) {
      clearTimeout(timerRef.current);
      timerRef.current = null;
    }

    setShots([]);
    setCurrentShot(null);
    setPhase('ready');
    setAim({ x: 75, y: 28 });
    setPower(65);
  }

  function finalMessage() {
    if (goals === 5) {
      return "Okay, you might actually be better than me";
    }

    if (goals >= 3) {
      return "Not bad. I'm demanding a rematch";
    }

    if (goals >= 1) {
      return "You got a few past me. I'll allow it";
    }

    return "CLEAN SHEET! This keeper isn't going anywhere";
  }

  const keeperX = currentShot?.keeperX ?? 50;

  const keeperRotation =
    keeperX < 45 ? -12 : keeperX > 55 ? 12 : 0;

  const keeperStyle = {
    '--keeper-x': `${keeperX}%`,
    '--keeper-rotation': `${keeperRotation}deg`,
    '--keeper-delay': `${currentShot?.reaction ?? 0}ms`,
    '--keeper-duration': `${
      currentShot
        ? Math.max(
            180,
            currentShot.duration * 0.72 -
              currentShot.reaction
          )
        : 300
    }ms`,
  } as CSSProperties;

  const ballStyle = currentShot
    ? ({
        '--target-x': `${currentShot.target.x}%`,
        '--target-y': `${currentShot.target.y}%`,
        '--flight-duration': `${currentShot.duration}ms`,
        '--deflect-x': `${
          currentShot.target.x < 50 ? -25 : 25
        }px`,
      } as CSSProperties)
    : undefined;

  return (
    <main className="hockey-game-page">
      <div className="hockey-game-container">
        <Link to="/" className="hockey-game-back">
          <ArrowLeft size={16} />
          BACK TO PORTFOLIO
        </Link>

        <header className="hockey-game-header">
          <p className="hockey-game-eyebrow">
            AFIF'S MINI ARCADE / 001
          </p>

          <h1>Beat the Keeper</h1>

          <p>
            Five penalty strokes. One Wisconsin goalkeeper.
            Think you can score past me?
          </p>
        </header>

        <section
          className="hockey-game-card"
          aria-label="Beat the Keeper game"
        >
          {/* SCOREBOARD */}
          <div className="hockey-game-scoreboard">
            <div>
              <span>STROKES</span>
              <strong>
                {shots.length} / {MAX_SHOTS}
              </strong>
            </div>

            <div>
              <span>GOALS</span>
              <strong>{goals}</strong>
            </div>

            <div>
              <span>SAVES</span>
              <strong>{saves}</strong>
            </div>

            <div>
              <span>MISSES</span>
              <strong>{misses}</strong>
            </div>
          </div>

          {/* DIFFICULTY */}
          <div className="hockey-game-settings">
            <div className="hockey-game-setting">
              <label htmlFor="hockey-difficulty">
                DIFFICULTY
              </label>

              <select
                id="hockey-difficulty"
                value={difficulty}
                disabled={shots.length > 0}
                onChange={(event) =>
                  setDifficulty(
                    event.target.value as Difficulty
                  )
                }
              >
                <option value="rookie">
                  ROOKIE
                </option>
                <option value="varsity">
                  VARSITY
                </option>
                <option value="all-american">
                  ALL-AMERICAN
                </option>
              </select>
            </div>

            <div className="hockey-game-setting">
              <span>KEEPER LEVEL</span>
              <strong>{config.label}</strong>
            </div>
          </div>

          {/* PITCH */}
          <div className="hockey-game-pitch">
            <div
              className="hockey-game-circle"
              aria-hidden="true"
            >
              <span>SHOOTING CIRCLE</span>
            </div>

            {/* GOAL */}
            <button
              ref={goalRef}
              type="button"
              className={`hockey-game-goal ${
                phase === 'ready'
                  ? 'hockey-game-goal--aiming'
                  : ''
              }`}
              onClick={aimAt}
              onKeyDown={keyboardAim}
              disabled={phase !== 'ready'}
              aria-label={
                `Aim at goal. Target ${Math.round(aim.x)}% ` +
                `across and ${Math.round(aim.y)}% down. ` +
                `Use arrow keys to adjust.`
              }
            >
              <span className="hockey-game-net" />

              {/* AIMING TARGET */}
              {phase === 'ready' && (
                <span
                  className="hockey-game-crosshair"
                  style={{
                    left: `${aim.x}%`,
                    top: `${aim.y}%`,
                  }}
                >
                  <Crosshair
                    size={26}
                    strokeWidth={2.5}
                  />
                </span>
              )}

              {/* GOALKEEPER */}

                <span
                key={`keeper-${shots.length}`}
                className={`hockey-game-photo-keeper ${
                    currentShot
                    ? 'hockey-game-photo-keeper--moving'
                    : ''
                }`}
                style={keeperStyle}
                >
                <img
                    src={goaliePhoto}
                    alt=""
                    draggable={false}
                />
                </span>


              {/* SHOT ANIMATION */}
              {currentShot && (
                <span
                  key={`shot-${shots.length}`}
                  className={`hockey-game-flying-ball hockey-game-flying-ball--${currentShot.outcome}`}
                  style={ballStyle}
                  aria-hidden="true"
                />
              )}
            </button>

            {/* PENALTY STROKE SPOT */}
            <div className="hockey-game-stroke-mark" />

            {phase === 'ready' && (
              <div className="hockey-game-stationary-ball" />
            )}

            {/* FIELD HOCKEY STICK */}
            <svg
              className="hockey-game-stick"
              viewBox="0 0 90 125"
              fill="none"
              aria-hidden="true"
            >
              <path
                d="M19 9 L64 91 Q73 105 61 112 Q51 118 39 111 L33 106"
                stroke="#251f20"
                strokeWidth="15"
                strokeLinecap="round"
                strokeLinejoin="round"
              />
              <path
                d="M19 9 L48 62"
                stroke="#cfaa67"
                strokeWidth="9"
                strokeLinecap="round"
              />
              <path
                d="M64 91 Q73 105 61 112 Q51 118 39 111 L33 106"
                stroke="#e8cf9d"
                strokeWidth="7"
                strokeLinecap="round"
              />
            </svg>

            <span className="hockey-game-stroke-label">
              6.4 M / PENALTY STROKE
            </span>
          </div>

          {/* POWER */}
          <div className="hockey-game-power">
            <div className="hockey-game-power-heading">
              <label htmlFor="hockey-power">
                <Zap size={16} />
                SHOT POWER
              </label>

              <strong>{power}%</strong>
            </div>

            <input
              id="hockey-power"
              type="range"
              min="20"
              max="100"
              step="1"
              value={power}
              disabled={phase !== 'ready'}
              onChange={(event) =>
                setPower(Number(event.target.value))
              }
              style={
                {
                  '--power-progress': `${
                    ((power - 20) / 80) * 100
                  }%`,
                } as CSSProperties
              }
            />

            <div className="hockey-game-power-labels">
              <span>CONTROL</span>
              <span>BALANCED</span>
              <span>POWER</span>
            </div>

            <p>
              More power makes your shot faster, but harder
              to aim accurately
            </p>
          </div>

          {/* RESULT */}
          <div
            className="hockey-game-message"
            aria-live="polite"
          >
            {finished ? (
              <>
                <Trophy size={24} />
                <strong>
                  FINAL SCORE: {goals} / {MAX_SHOTS}
                </strong>
                <p>{finalMessage()}</p>
              </>
            ) : phase === 'flying' ? (
              <>
                <strong>HERE IT COMES! 🏑</strong>
                <p>Watch the keeper...</p>
              </>
            ) : phase === 'result' &&
              currentShot?.outcome === 'goal' ? (
              <>
                <strong>GOOOOAL! 🏑</strong>
                <p>You got one past me!</p>
              </>
            ) : phase === 'result' &&
              currentShot?.outcome === 'save' ? (
              <>
                <strong>WHAT A SAVE! 🧤</strong>
                <p>Not getting past this keeper</p>
              </>
            ) : phase === 'result' &&
              currentShot?.outcome === 'miss' ? (
              <>
                <strong>WIDE OF THE GOAL!</strong>
                <p>Maybe take a little power off next time</p>
              </>
            ) : (
              <>
                <Crosshair size={19} />
                <strong>PICK YOUR SPOT</strong>
                <p>
                  Click or tap inside the goal to aim.
                  Then take your shot
                </p>
              </>
            )}
          </div>

          {/* CONTROLS */}
          {phase === 'ready' && (
            <button
              type="button"
              className="hockey-game-next"
              onClick={takeShot}
            >
              <Zap size={18} />
              TAKE THE SHOT →
            </button>
          )}

          {phase === 'flying' && (
            <button
              type="button"
              className="hockey-game-next"
              disabled
            >
              BALL IN FLIGHT...
            </button>
          )}

          {phase === 'result' && !finished && (
            <button
              type="button"
              className="hockey-game-next"
              onClick={nextShot}
            >
              NEXT STROKE →
            </button>
          )}

          {finished && (
            <button
              type="button"
              className="hockey-game-next"
              onClick={restart}
            >
              <RotateCcw size={18} />
              PLAY AGAIN
            </button>
          )}
        </section>

        <p className="hockey-game-footnote">
          Made for fun, inspired by my time as a goalkeeper
          for the Wisconsin Club Field Hockey Team
        </p>
      </div>
    </main>
  );
}
